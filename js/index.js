// Логика раскрывашек и переходов
document.addEventListener('DOMContentLoaded', () => {
  // Универсальная привязка дропдауна
  const bindDropdown = (btnId, contentId) => {
    const btn = document.getElementById(btnId);
    const content = document.getElementById(contentId);
    if (!btn || !content) return;

    btn.addEventListener('click', () => {
      if (typeof toggleDropdown === 'function') {
        toggleDropdown(btn, content);
      } else {
        btn.classList.toggle('open');
        content.classList.toggle('open');
      }
    });
  };

  bindDropdown('manifestBtn', 'manifestContent');
  bindDropdown('uberBtn', 'uberContent');
  bindDropdown('authorSevaBtn', 'authorSevaContent');
  bindDropdown('authorMishmashBtn', 'authorMishmashContent');
  bindDropdown('authorHuBtn', 'authorHuContent');

  // Переходы по сценам
  const go = (id, href) => {
    const el = document.getElementById(id);
    if (!el) return;
    el.addEventListener('click', () => {
      window.location.href = href;
    });
  };

  go('locationTempelhofBtn', 'tempelhof.html');
  go('locationApothekeBtn', 'apotheke.html');
  go('locationFriedrichshainBtn', 'friedrichshain.html');
  go('locationBalconyBtn', 'balcony.html');
});
